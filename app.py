@app.post("/api/opportunities")
def create_opportunity():
    data = request.get_json(silent=True)
    problem = validate_opportunity(data)
    if problem:
        return error_response(problem, 400)
    status = data.get("status", "Open")
    connection = None
    cursor = None
    try:
        connection = get_db_connection()
        cursor = connection.cursor()
        sql = """INSERT INTO opportunities
        (research_title, research_description, research_area, faculty_name,
         department, required_skills, available_positions, application_deadline, status)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)"""
        values = (
            data["research_title"].strip(), data["research_description"].strip(),
            data["research_area"].strip(), data["faculty_name"].strip(),
            data["department"].strip(), data["required_skills"].strip(),
            data["available_positions"], data["application_deadline"], status
        )
        cursor.execute(sql, values)
        connection.commit()
        new_id = cursor.lastrowid
        return jsonify({"message": "Research opportunity created.", "id": new_id}), 201
    except Error:
        app.logger.exception("Unable to create opportunity")
        if connection:
            connection.rollback()
        return error_response("Database error while creating the opportunity.", 500)
    finally:
        if cursor:
            cursor.close()
        if connection and connection.is_connected():
            connection.close()

