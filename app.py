import os
from datetime import date
from flask import Flask, jsonify, render_template, request
import mysql.connector
from mysql.connector import Error, IntegrityError

app = Flask(__name__)

def get_db_connection():
    """Create a fresh MySQL connection using environment variables."""
    return mysql.connector.connect(
        host=os.getenv("DB_HOST", "127.0.0.1"),
        port=int(os.getenv("DB_PORT", "3306")),
        user=os.getenv("DB_USER", "root"),
        password=os.getenv("DB_PASSWORD", ""),
        database=os.getenv("DB_NAME", "research_portal"),
    )

def error_response(message, status):
    return jsonify({"error": message}), status

def validate_opportunity(data, partial=False):
    if not isinstance(data, dict):
        return "Request body must be a JSON object."

    fields = {
        "research_title": (200, str),
        "research_description": (None, str),
        "research_area": (100, str),
        "faculty_name": (150, str),
        "department": (100, str),
        "required_skills": (None, str),
        "available_positions": (None, int),
        "application_deadline": (None, str),
        "status": (None, str),
    }
    required = [
        "research_title", "research_description", "research_area",
        "faculty_name", "department", "required_skills",
        "available_positions", "application_deadline"
    ]
    if not partial:
        missing = [key for key in required if key not in data or data[key] is None or data[key] == ""]
        if missing:
            return "Missing required field(s): " + ", ".join(missing)

    for key, value in data.items():
        if key not in fields:
            if key == "id":
                return "The id field is generated by the server."
            return f"Unknown field: {key}"
        if value is None:
            return f"{key} cannot be null."
        if key in ("research_title", "research_description", "research_area",
                   "faculty_name", "department", "required_skills"):
            if not isinstance(value, str) or not value.strip():
                return f"{key} must be a non-empty string."
            limit = fields[key][0]
            if limit and len(value.strip()) > limit:
                return f"{key} must be at most {limit} characters."
        elif key == "available_positions":
            if isinstance(value, bool) or not isinstance(value, int) or value < 1:
                return "available_positions must be a positive integer."
        elif key == "application_deadline":
            if not isinstance(value, str):
                return "application_deadline must be a date in YYYY-MM-DD format."
            try:
                date.fromisoformat(value)
            except ValueError:
                return "application_deadline must be a valid date in YYYY-MM-DD format."
        elif key == "status":
            if value not in ("Open", "Closed"):
                return "status must be either Open or Closed."
    if not partial and "status" in data and data["status"] not in ("Open", "Closed"):
        return "status must be either Open or Closed."
    return None

def row_to_dict(row):
    if row is None:
        return None
    result = dict(row)
    if result.get("application_deadline"):
        result["application_deadline"] = result["application_deadline"].isoformat()
    return result

