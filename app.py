@app.get("/api/opportunities")
def get_opportunities():
    connection = None
    cursor = None
    try:
        connection = get_db_connection()
        cursor = connection.cursor(dictionary=True)
        cursor.execute("SELECT * FROM opportunities ORDER BY id DESC")
        return jsonify([row_to_dict(row) for row in cursor.fetchall()]), 200
    except Error:
        app.logger.exception("Unable to retrieve opportunities")
        return error_response("Database error while retrieving opportunities.", 500)
    finally:
        if cursor:
            cursor.close()
        if connection and connection.is_connected():
            connection.close()

